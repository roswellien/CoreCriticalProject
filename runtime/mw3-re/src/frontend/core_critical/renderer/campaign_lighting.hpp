inline const MissionEnvironment *
find_builtin_environment(std::string_view id) noexcept {
  if (id.empty()) {
    return nullptr;
  }
  const auto &db = builtin_mission_database();
  for (const auto &env : db) {
    if (id == env.id) {
      return &env;
    }
  }
  return nullptr;
}

inline const MissionEnvironment *
find_builtin_environment(const char *id) noexcept {
  return id ? find_builtin_environment(std::string_view(id)) : nullptr;
}

struct ResolvedMissionLighting {
  bool has_profile{false};
  const MissionEnvironment *environment{nullptr};
  EnvironmentPolicy policy{};
};

inline ResolvedMissionLighting
resolve_mission_lighting(std::string_view id) noexcept {
  ResolvedMissionLighting result{};
  const MissionEnvironment *env = find_builtin_environment(id);
  if (!env) {
    result.has_profile = false;
    result.environment = nullptr;
    result.policy = resolve_environment_policy(id, false);
    return result;
  }
  result.has_profile = true;
  result.environment = env;
  result.policy = resolve_environment_policy(id, env->is_interior);
  return result;
}

inline ResolvedMissionLighting
resolve_mission_lighting(const char *id) noexcept {
  return resolve_mission_lighting(id ? std::string_view(id)
                                     : std::string_view{});
}

