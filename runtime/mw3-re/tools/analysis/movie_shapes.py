"""The movies' shapes for the program's built-in table (src/mech3/movie_shape_table.cpp,
docs/fmv.md section 8): every distinct video\\*.AVI of the folders given,
converted and measured by mw3import --shapes (the program's own measurement),
written as the table. Our measured numbers, not the game's data.

    .venv/bin/python tools/analysis/movie_shapes.py [--check LINE ...] DIR...

DIR: an install or a disc's folder (its video or VIDEO folder is read).
Files with the same bytes are measured once; the same key measured to
different runs stops the tool. --check: a line that must come out as given
(the PC's own cache, measured through Windows' Indeo codec).
"""
import argparse
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / 'src' / 'mech3' / 'movie_shape_table.cpp'


def avis(folder):
    for sub in folder.iterdir():
        if sub.is_dir() and sub.name.lower() == 'video':
            yield from sorted(p for p in sub.iterdir() if p.suffix.lower() == '.avi')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('dirs', nargs='+', type=Path)
    ap.add_argument('--check', action='append', default=[])
    ap.add_argument('--importer', type=Path, default=ROOT / 'build' / 'mw3import')
    a = ap.parse_args()
    seen, lines, sources = {}, {}, {}
    with tempfile.TemporaryDirectory() as tmp:
        for d in a.dirs:
            for avi in avis(d):
                digest = hashlib.sha256(avi.read_bytes()).hexdigest()
                sources.setdefault(digest, []).append(str(avi))
                if digest in seen:
                    continue
                seen[digest] = avi
                one = Path(tmp) / digest[:12]
                (one / 'video').mkdir(parents=True)
                (one / 'video' / avi.name).symlink_to(avi.resolve())
                out = subprocess.run([str(a.importer), '--install', str(one), '--write-dir', str(one / 'out'), '--shapes'],
                                     capture_output=True, text=True)
                got = [l[6:] for l in out.stdout.splitlines() if l.startswith('shape ')]
                if out.returncode or len(got) != 1:
                    raise SystemExit(f'{avi}: mw3import failed\n{out.stderr}')
                key = got[0].split()[0]
                if key in lines and lines[key] != got[0]:
                    raise SystemExit(f'{key}: measured two ways:\n  {lines[key]}\n  {got[0]}')
                lines[key] = got[0]
                print(got[0], flush=True)
    for want in a.check:
        key = want.split()[0]
        if lines.get(key) != want:
            raise SystemExit(f'check: {want!r} came out {lines.get(key)!r}')
    body = ''.join(f'      "{lines[k]}",\n' for k in sorted(lines))
    TABLE.write_text(f'''// Generated by tools/analysis/movie_shapes.py: the shipped movies' shapes
// (movie_shape.h), measured by the program's own code on {len(lines)} movies
// ({sum(len(v) for v in sources.values())} files across the folders given, {len(seen)} distinct).
// Our numbers, not the game's data. Regenerate rather than edit.
#include "mech3/movie_shape.h"

namespace mech3 {{

const std::vector<std::string>& movie_shape_table() {{
  static const std::vector<std::string> lines = {{
{body}  }};
  return lines;
}}

}}  // namespace mech3
''')
    print(f'{len(lines)} movies ({len(seen)} distinct files of {sum(len(v) for v in sources.values())}) into {TABLE.relative_to(ROOT)}; '
          f'{len(a.check)} checks passed')


if __name__ == '__main__':
    main()
