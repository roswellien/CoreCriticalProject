"""Generate the MFC42 stage dispatch includes from pinned lift_closure.py reports.

mfc_entries.inc (inside namespace mf): body declarations and the address-sorted table of lifted
entries. mfc_routers.inc (global scope): every direct-call symbol mw34_mfc_sub_<addr> (renamed by
lift_closure.py) the lifted objects reference, routed to the active stage, and each object's
undefined-flag representative. mfc_objects.txt: the object stems (one per lifted component) that
build.ps1 links. Several reports are merged in order; a later report's object replaces an earlier one at the same
entry (repair lifts); tables carry addresses and
symbol names only (no original code). Direct targets without a body (failed or unlifted) keep their
router, which stops typed when reached.
Usage: python -B gen_mfc_dispatch.py LIFT_DIR REPORT_SHA256 [LIFT_DIR REPORT_SHA256 ...]
"""
import hashlib,json,sys
from pathlib import Path
sys.dont_write_bytecode=True
HERE=Path(__file__).resolve().parent
def main(*args):
    assert args and len(args)%2==0,'LIFT_DIR REPORT_SHA256 pairs'
    rows=[];failed={};names=[]
    for lift_dir,digest in zip(args[::2],args[1::2]):
        data=(Path(lift_dir)/'report.json').read_bytes();assert hashlib.sha256(data).hexdigest()==digest,'Exact pinned lift report '+lift_dir
        R=json.loads(data);failed.update(R.get('failed',{}));names.append('%s (%s)'%(Path(lift_dir).name,digest))
        later={v['entry'] for v in R['components'].values()}|{int(k[2:],16) for k in R.get('failed',{}) if k.startswith('m_')}  # failed re-lifts also retire the earlier object
        rows=[r for r in rows if r[0] not in later]+[(v['entry'],k,v,Path(lift_dir).resolve()) for k,v in R['components'].items()]  # a later report (repair lift) overrides
    rows.sort(key=lambda r:r[0])
    assert len({e for e,*_ in rows})==len(rows),'One lifted body per entry address'
    assert not any(b.startswith('sub_') for _,_,v,_ in rows for b in v['bridges']),'Direct calls renamed into mw34_mfc_'
    subs=sorted({int(b[13:],16) for _,_,v,_ in rows for b in v['bridges'] if b.startswith('mw34_mfc_sub_')})
    missing=sorted(set(subs)-{e for e,*_ in rows})
    und=sorted(b for _,_,v,_ in rows for b in v['bridges'] if b.endswith('_undefined_8'))
    head='// Generated by gen_mfc_dispatch.py from %s. Do not edit.\n'%', '.join(names)
    e=[head]+['extern "C" void*mw34_attach_%s_body(State*,unsigned,void*) noexcept(false);\n'%k for _,k,_,_ in rows]
    e.append('inline constexpr std::array<Entry,%d>mfc_entries{{%s}};\n'%(len(rows),','.join('{0x%x,mw34_attach_%s_body}'%(a,k) for a,k,_,_ in rows)))
    r=[head]+['extern "C" void*mw34_mfc_sub_%x(State*s,unsigned a,void*p)noexcept(false){return mf_called(s,a,p);}\n'%a for a in subs]
    r+=['extern "C" unsigned char %s()noexcept(false){return mf_undefined();}\n'%u for u in und]
    (HERE/'mfc_entries.inc').write_text(''.join(e));(HERE/'mfc_routers.inc').write_text(''.join(r))
    (HERE/'mfc_objects.txt').write_text(''.join((d/k).as_posix()+'\n' for _,k,_,d in rows))
    print(len(rows),'entries',len(subs),'direct routers',len(und),'undefined representatives',len(failed),'failed lifts',len(missing),'direct targets without a body')
if __name__=='__main__':main(*sys.argv[1:])
