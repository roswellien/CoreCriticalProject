using System.Diagnostics;
using System.IO;
using System.Text;
using System.Text.Json;

namespace MW3RemasterLauncher.Core;

/// <summary>An arena multiplayer map listed by <c>mw3 --arena-catalog</c>.</summary>
public sealed record ArenaCatalogMap(string Id, string Name)
{
    public string DisplayLabel => string.IsNullOrWhiteSpace(Name) || string.Equals(Name, Id, StringComparison.OrdinalIgnoreCase)
        ? Id
        : $"{Name} ({Id})";
}

/// <summary>A stock mech loadout listed by <c>mw3 --arena-catalog</c>.</summary>
public sealed record ArenaCatalogLoadout(int Index, string Name, JsonElement RawData)
{
    public string DisplayLabel => string.IsNullOrWhiteSpace(Name)
        ? $"Loadout {Index}"
        : $"{Index}: {Name}";
}

/// <summary>A mech chassis and its stock loadouts from <c>mw3 --arena-catalog</c>.</summary>
public sealed record ArenaCatalogMech(string Id, string Name, IReadOnlyList<ArenaCatalogLoadout> Loadouts, JsonElement RawData)
{
    public string DisplayLabel => string.IsNullOrWhiteSpace(Name) || string.Equals(Name, Id, StringComparison.OrdinalIgnoreCase)
        ? Id
        : $"{Name} ({Id})";
}

/// <summary>An AI pilot record shipped in the game's mission archives.</summary>
public sealed record ArenaCatalogPreset(string World, string Mission, string Record, string Mech, JsonElement Numbers)
{
    public string DisplayLabel => $"{World} {Mission} {Record}";
}

/// <summary>
/// Loads and caches the game's own AI Arena lists (<c>catalog.json</c>) generated by
/// <c>mw3 --install &lt;GAMEDIR&gt; --arena-catalog &lt;DIR&gt;</c>.
/// </summary>
public sealed class ArenaCatalog
{
    public const int ExpectedVersion = 1;
    public const string CatalogFileName = "catalog.json";
    public const string StampFileName = "stamp.json";

    public IReadOnlyList<ArenaCatalogMap> Maps { get; }
    public IReadOnlyList<ArenaCatalogMech> Mechs { get; }
    public IReadOnlyList<ArenaCatalogPreset> Presets { get; }
    public IReadOnlyList<string> TimeOfDayOptions { get; }

    public ArenaCatalog(
        IReadOnlyList<ArenaCatalogMap> maps,
        IReadOnlyList<ArenaCatalogMech> mechs,
        IReadOnlyList<ArenaCatalogPreset> presets,
        IReadOnlyList<string>? timeOfDayOptions = null)
    {
        Maps = maps ?? throw new ArgumentNullException(nameof(maps));
        Mechs = mechs ?? throw new ArgumentNullException(nameof(mechs));
        Presets = presets ?? throw new ArgumentNullException(nameof(presets));
        TimeOfDayOptions = timeOfDayOptions ?? Array.Empty<string>();
    }

    public ArenaCatalogMech? FindMech(string mechId) =>
        Mechs.FirstOrDefault(mech => string.Equals(mech.Id, mechId, StringComparison.Ordinal));

    /// <summary>Parse a <c>catalog.json</c> file from disk without requiring a game install.</summary>
    public static ArenaCatalog LoadFromFile(string catalogJsonPath)
    {
        if (!File.Exists(catalogJsonPath))
            throw new FileNotFoundException("Arena catalog file was not found.", catalogJsonPath);
        return ParseJson(File.ReadAllText(catalogJsonPath, Encoding.UTF8));
    }

    /// <summary>Parse <c>catalog.json</c> text and verify its version and required arrays.</summary>
    public static ArenaCatalog ParseJson(string jsonText)
    {
        if (string.IsNullOrWhiteSpace(jsonText))
            throw new InvalidDataException("Arena catalog JSON is empty.");

        using var document = JsonDocument.Parse(jsonText);
        var root = document.RootElement;
        if (root.ValueKind != JsonValueKind.Object)
            throw new InvalidDataException("Arena catalog root must be a JSON object.");

        if (!root.TryGetProperty("version", out var versionElement) ||
            versionElement.ValueKind != JsonValueKind.Number ||
            !versionElement.TryGetInt32(out var version))
        {
            throw new InvalidDataException("Arena catalog is missing a whole-number version.");
        }

        if (version != ExpectedVersion)
        {
            throw new InvalidDataException($"Arena catalog version {version} is not supported (expected {ExpectedVersion}).");
        }

        if (!root.TryGetProperty("maps", out var mapsElement) || mapsElement.ValueKind != JsonValueKind.Array)
            throw new InvalidDataException("Arena catalog is missing its maps array.");
        if (!root.TryGetProperty("mechs", out var mechsElement) || mechsElement.ValueKind != JsonValueKind.Array)
            throw new InvalidDataException("Arena catalog is missing its mechs array.");
        if (!root.TryGetProperty("presets", out var presetsElement) || presetsElement.ValueKind != JsonValueKind.Array)
            throw new InvalidDataException("Arena catalog is missing its presets array.");

        var maps = new List<ArenaCatalogMap>();
        var mapIds = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in mapsElement.EnumerateArray())
        {
            if (item.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException("Arena catalog map entry must be a JSON object.");
            var id = ReadRequiredString(item, "id", "maps");
            if (!mapIds.Add(id))
            {
                throw new InvalidDataException($"Arena catalog lists map \"{id}\" twice.");
            }
            var name = ReadRequiredString(item, "name", "maps", allowEmpty: true);
            maps.Add(new ArenaCatalogMap(id, string.IsNullOrEmpty(name) ? id : name));
        }

        var mechs = new List<ArenaCatalogMech>();
        var mechIds = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in mechsElement.EnumerateArray())
        {
            if (item.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException("Arena catalog mech entry must be a JSON object.");
            var id = ReadRequiredString(item, "id", "mechs");
            if (!mechIds.Add(id))
            {
                throw new InvalidDataException($"Arena catalog lists mech \"{id}\" twice.");
            }
            var name = ReadRequiredString(item, "name", "mechs", allowEmpty: true);
            if (!item.TryGetProperty("loadouts", out var loadoutsElement) || loadoutsElement.ValueKind != JsonValueKind.Array)
                throw new InvalidDataException($"Arena catalog mech '{id}' is missing its loadouts array.");

            var loadouts = new List<ArenaCatalogLoadout>();
            var loadoutIndices = new HashSet<int>();
            var listIndex = 0;
            foreach (var loadoutItem in loadoutsElement.EnumerateArray())
            {
                if (loadoutItem.ValueKind != JsonValueKind.Object)
                    throw new InvalidDataException($"Arena catalog loadout in mech '{id}' must be a JSON object.");
                var loadoutName = loadoutItem.TryGetProperty("name", out var nameProp) && nameProp.ValueKind == JsonValueKind.String
                    ? nameProp.GetString() ?? ""
                    : "";
                var explicitIndex = loadoutItem.TryGetProperty("index", out var indexProp) &&
                    indexProp.ValueKind == JsonValueKind.Number && indexProp.TryGetInt32(out var parsedIndex)
                    ? parsedIndex
                    : listIndex;
                if (!loadoutIndices.Add(explicitIndex))
                {
                    throw new InvalidDataException($"Arena catalog mech \"{id}\" lists loadout index {explicitIndex} twice.");
                }
                loadouts.Add(new ArenaCatalogLoadout(explicitIndex, loadoutName, loadoutItem.Clone()));
                listIndex++;
            }

            mechs.Add(new ArenaCatalogMech(id, string.IsNullOrEmpty(name) ? id : name, loadouts, item.Clone()));
        }

        var presets = new List<ArenaCatalogPreset>();
        foreach (var item in presetsElement.EnumerateArray())
        {
            if (item.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException("Arena catalog preset entry must be a JSON object.");
            var world = ReadRequiredString(item, "world", "presets");
            var mission = ReadRequiredString(item, "mission", "presets");
            var record = ReadRequiredString(item, "record", "presets");
            var mech = item.TryGetProperty("mech", out var mechProp) && mechProp.ValueKind == JsonValueKind.String
                ? mechProp.GetString() ?? ""
                : "";
            var numbers = item.TryGetProperty("numbers", out var numbersProp)
                ? numbersProp.Clone()
                : default;
            presets.Add(new ArenaCatalogPreset(world, mission, record, mech, numbers));
        }

        var timesOfDay = new List<string>();
        if (root.TryGetProperty("times_of_day", out var timesElement))
        {
            if (timesElement.ValueKind != JsonValueKind.Array)
                throw new InvalidDataException("Arena catalog times_of_day must be an array of strings.");
            foreach (var timeItem in timesElement.EnumerateArray())
            {
                if (timeItem.ValueKind != JsonValueKind.String || string.IsNullOrWhiteSpace(timeItem.GetString()))
                    throw new InvalidDataException("Arena catalog times_of_day entries must be non-empty strings.");
                timesOfDay.Add(timeItem.GetString()!);
            }
        }

        return new ArenaCatalog(maps, mechs, presets, timesOfDay);
    }

    private static string ReadRequiredString(JsonElement element, string propertyName, string sectionName, bool allowEmpty = false)
    {
        if (!element.TryGetProperty(propertyName, out var value) || value.ValueKind != JsonValueKind.String)
            throw new InvalidDataException($"Arena catalog {sectionName} entry is missing string '{propertyName}'.");
        var text = value.GetString() ?? "";
        if (!allowEmpty && string.IsNullOrWhiteSpace(text))
            throw new InvalidDataException($"Arena catalog {sectionName} entry has an empty '{propertyName}'.");
        return text;
    }

    /// <summary>
    /// Resolve the integrity-checked bundled MW3-RE executable and ensure the cached catalog
    /// under <c>&lt;dataRoot&gt;/arena/catalog/catalog.json</c> matches that executable build.
    /// </summary>
    public static async Task<ArenaCatalog> EnsureCatalogAsync(
        NativeGameRunner runner,
        string gamePath,
        string dataRoot,
        bool forceRefresh = false,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(runner);
        var validation = GameValidator.Validate(gamePath);
        if (!validation.IsValid)
            throw new InvalidOperationException("Cannot load AI Arena catalog: " + validation.StatusMessage);

        var runtimeRoot = runner.RequireBundledMw3Re();
        var contract = Mw3ReRuntimeContract.ReadStructure(runtimeRoot);
        return await EnsureCatalogForExecutableAsync(
            contract.Executable,
            validation.GameDirectory,
            dataRoot,
            forceRefresh,
            cancellationToken).ConfigureAwait(false);
    }

    /// <summary>
    /// Ensure the cached catalog is up to date for the specified <c>mw3.exe</c> path and game folder.
    /// </summary>
    public static async Task<ArenaCatalog> EnsureCatalogForExecutableAsync(
        string executablePath,
        string gameDirectory,
        string dataRoot,
        bool forceRefresh = false,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var fullExePath = Path.GetFullPath(executablePath);
        if (!File.Exists(fullExePath))
            throw new FileNotFoundException("The MW3-RE executable was not found.", fullExePath);

        var arenaRoot = Path.Combine(Path.GetFullPath(dataRoot), "arena");
        var catalogFolder = Path.Combine(arenaRoot, "catalog");
        var catalogJsonPath = Path.Combine(catalogFolder, CatalogFileName);
        var stampPath = Path.Combine(catalogFolder, StampFileName);
        var currentStamp = BuildExecutableStamp(fullExePath);

        if (forceRefresh || !IsCatalogCurrent(catalogJsonPath, stampPath, currentStamp))
        {
            Directory.CreateDirectory(catalogFolder);
            // Use an isolated write folder so generating the catalog never overwrites the
            // player's normal mw3.log or settings.reg.
            var writeDirectory = Path.Combine(arenaRoot, "catalog-write");
            Directory.CreateDirectory(writeDirectory);

            var startInfo = new ProcessStartInfo(fullExePath)
            {
                WorkingDirectory = Path.GetDirectoryName(fullExePath) ?? arenaRoot,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                CreateNoWindow = true,
                StandardOutputEncoding = Encoding.UTF8,
                StandardErrorEncoding = Encoding.UTF8
            };
            startInfo.ArgumentList.Add("--install");
            startInfo.ArgumentList.Add(Path.GetFullPath(gameDirectory));
            startInfo.ArgumentList.Add("--arena-catalog");
            startInfo.ArgumentList.Add(catalogFolder);
            startInfo.ArgumentList.Add("--write-dir");
            startInfo.ArgumentList.Add(writeDirectory);

            cancellationToken.ThrowIfCancellationRequested();
            using var process = Process.Start(startInfo)
                ?? throw new InvalidOperationException("Failed to start MW3-RE for arena catalog generation.");

            var (stdoutText, stderrText) = await WaitForCatalogProcessAsync(
                process,
                ProductionCatalogTimeout,
                cancellationToken).ConfigureAwait(false);

            if (process.ExitCode != 0)
            {
                var detail = FirstNonEmptyDetail(stderrText, stdoutText, Path.Combine(writeDirectory, "mw3.log"));
                var suffix = string.IsNullOrWhiteSpace(detail) ? "" : Environment.NewLine + detail;
                throw new InvalidOperationException(
                    $"mw3 --arena-catalog failed (exit {process.ExitCode}).{suffix}");
            }

            File.WriteAllText(stampPath, JsonSerializer.Serialize(currentStamp), new UTF8Encoding(false));
        }

        return LoadFromFile(catalogJsonPath);
    }

    private static readonly TimeSpan ProductionCatalogTimeout = TimeSpan.FromMinutes(2);

    /// <summary>
    /// Wait for the catalog generation process to exit within the specified timeout.
    /// On timeout or caller cancellation, kills the child process tree, awaits termination/drain,
    /// and throws a TimeoutException or rethrows the caller's cancellation.
    /// </summary>
    public static async Task<(string Stdout, string Stderr)> WaitForCatalogProcessAsync(
        Process process,
        TimeSpan timeout,
        CancellationToken cancellationToken = default)
    {
        using var timeoutCancellationSource = new CancellationTokenSource(timeout);
        using var linkedCancellationSource = CancellationTokenSource.CreateLinkedTokenSource(timeoutCancellationSource.Token, cancellationToken);

        var stdoutTask = process.StartInfo.RedirectStandardOutput
            ? process.StandardOutput.ReadToEndAsync()
            : Task.FromResult(string.Empty);
        var stderrTask = process.StartInfo.RedirectStandardError
            ? process.StandardError.ReadToEndAsync()
            : Task.FromResult(string.Empty);

        try
        {
            await process.WaitForExitAsync(linkedCancellationSource.Token).ConfigureAwait(false);
            process.WaitForExit();

            var stdoutText = await stdoutTask.ConfigureAwait(false);
            var stderrText = await stderrTask.ConfigureAwait(false);
            return (stdoutText, stderrText);
        }
        catch (OperationCanceledException)
        {
            try
            {
                if (!process.HasExited)
                    process.Kill(entireProcessTree: true);
            }
            catch (InvalidOperationException)
            {
                // The process can exit while cancellation requests its termination.
            }

            // Draining both pipes releases the readers before the caller disposes the process.
            await process.WaitForExitAsync().ConfigureAwait(false);
            await Task.WhenAll(stdoutTask, stderrTask).ConfigureAwait(false);
            cancellationToken.ThrowIfCancellationRequested();

            throw new TimeoutException("Generating the arena catalog took longer than 2 minutes");
        }
    }

    private sealed record ExecutableStamp(string Exe, long Size, long MtimeTicks);

    private static ExecutableStamp BuildExecutableStamp(string fullExePath)
    {
        var info = new FileInfo(fullExePath);
        return new ExecutableStamp(fullExePath, info.Length, info.LastWriteTimeUtc.Ticks);
    }

    private static bool IsCatalogCurrent(string catalogJsonPath, string stampPath, ExecutableStamp expected)
    {
        if (!File.Exists(catalogJsonPath) || !File.Exists(stampPath))
            return false;
        try
        {
            var saved = JsonSerializer.Deserialize<ExecutableStamp>(File.ReadAllText(stampPath, Encoding.UTF8));
            return saved != null &&
                string.Equals(saved.Exe, expected.Exe, StringComparison.OrdinalIgnoreCase) &&
                saved.Size == expected.Size &&
                saved.MtimeTicks == expected.MtimeTicks;
        }
        catch
        {
            return false;
        }
    }

    private static string FirstNonEmptyDetail(string stderrText, string stdoutText, string runtimeLogPath)
    {
        if (!string.IsNullOrWhiteSpace(stderrText))
            return stderrText.Trim();
        if (!string.IsNullOrWhiteSpace(stdoutText))
            return stdoutText.Trim();
        try
        {
            if (File.Exists(runtimeLogPath))
            {
                var logText = File.ReadAllText(runtimeLogPath, Encoding.UTF8).Trim();
                if (logText.Length > 2000)
                    logText = logText[^2000..];
                return logText;
            }
        }
        catch { }
        return "";
    }
}
