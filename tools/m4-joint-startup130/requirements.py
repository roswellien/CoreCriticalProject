def main(supplement, name):
    module = importlib.util.spec_from_file_location(
        'acceptance130_requirements', Path(__file__).with_name('acceptance.py'))
    acceptance = importlib.util.module_from_spec(module)
    module.loader.exec_module(acceptance)
    more = {} if supplement == '-' else json.loads(
        Path(supplement).read_text(encoding='utf-8-sig'),
        object_pairs_hook=acceptance.unique_object)
    acceptance.need(not set(ROWS) & set(more), 'No overriding frozen measured requirements')
    rows = {label:dict(path='reports/' + path, equal=equal)
            for label, (path, equal) in ROWS.items()} | more
    acceptance.need(set(rows) == acceptance.REQUIRED, 'Every pending semantic gate supplied')
    for label, item in rows.items():
        acceptance.need(set(item) == {'path', 'equal'}, 'Exact gate requirement schema')
        report = acceptance.read(ROOT / item['path'])
        acceptance.need(report['passed'] is True and len(item['equal']) >= 2,
                        'Passed substantial measured gate ' + label)
        for field, expected in item['equal'].items():
            actual = acceptance.extent_value(report, field)
            acceptance.need(type(actual) is type(expected) and actual == expected,
                            'Exact measured130 gate ' + label + ':' + field)
    out = ROOT / 'reports/m4-joint-startup130-root' / name
    acceptance.need(not out.exists(), 'Fresh complete specification')
    out.write_text(json.dumps(rows, indent=2) + '\n')
    print(json.dumps(dict(path=str(out), sha256=acceptance.sha(out), gates=len(rows),
        predicates=sum(len(row['equal']) for row in rows.values()), initializer_credit=0)))


if __name__ == '__main__':
    main(*sys.argv[1:])
