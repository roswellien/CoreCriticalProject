"""Pin sparse complete original code and exact default pages for 26 connected roots.

Generated bytes/instructions stay private. This is a filtered table sequence,
not execution or admission of all intervening initializer slots.
"""
from pathlib import Path
import hashlib,json,struct,sys
sys.dont_write_bytecode=True
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'tools/analysis'))
from pe import PEImage,read_binary

IMAGE_SHA='95bc2c114c9b2e5c5ada8e40ca78cc79470f862e45313ffad0d1e8e6d4d916bf'
INVENTORY_SHA='81c018087a23a75d0296565e233609fbe00bd6881a8329c6b1aeff16c9dd7d5a'
CAPTURE=0x410a80
DATA_PAGES=(0x5c8000,0x5c9000,0x5cb000,0x5cc000,0x5e0000,0x5e1000,0x5e8000,0x604000,0x605000,0x60b000)
WRITABLE=(0x604000,0x605000,0x60b000)
STACK=0x20001000

def require(ok,reason):
    if not ok:raise ValueError(reason)
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def bind(path):
    path=Path(path).resolve()
    return {'path':str(path),'size_bytes':path.stat().st_size,'sha256':sha(path)}
def page_bytes(image,address):
    result=bytearray(4096)
    for off in range(4096):
        va=address+off
        sections=[s for s in image.sections if image.image_base+s['virtual_address']<=va<image.image_base+s['virtual_address']+max(s['virtual_size'],s['raw_size'])]
        require(len(sections)==1,'Unmapped/overlapping owned game page')
        section=sections[0];within=va-image.image_base-section['virtual_address']
        if within<section['raw_size']:result[off]=image.data[section['raw_offset']+within]
    return bytes(result)
def main():
    out=Path(sys.argv[1]).resolve()
    require(out.parent==ROOT/'reports/m4-mixed-startup' and out.name.startswith('original-'),'Assigned private original output required')
    require(not out.exists(),'Entirely fresh extraction directory required')
    inventory=ROOT/'reports/m4-initializer-inventory/r1'
    require(sha(inventory/'report.json')==INVENTORY_SHA,'Reviewed full inventory changed')
    pin_doc=json.loads((inventory/'pins.json').read_text())
    for item in pin_doc['bindings']:
        require(Path(item['path']).stat().st_size==item['size_bytes'] and sha(item['path'])==item['sha256'],'Inventory physical binding changed')
    report=json.loads((inventory/'report.json').read_text())
    graphs=json.loads((inventory/'function-graphs.json').read_text())
    rows=json.loads((inventory/'instruction-lookup.json').read_text())
    selected=[item for item in report['roots'] if item.get('direct_branch_graph_import_free')]
    require(len(selected)==26 and sum(bool(x['FP_instruction_count']) for x in selected)==10,'Reviewed selected root set differs')
    require([x['slot'] for x in selected]==sorted(x['slot'] for x in selected),'Original table ordering differs')
    image_path=ROOT/'MW3/Mech3.exe';data=read_binary(image_path)
    require(len(data)==2384384 and hashlib.sha256(data).hexdigest()==IMAGE_SHA,'Exact admitted image required')
    image=PEImage(data)
    require(image.image_base==0x400000,'Original preferred image base differs')
    for item in selected:
        offset,_=image.rva_range(item['slot']-image.image_base,4)
        require(struct.unpack_from('<I',data,offset)[0]==item['entry'],'Literal original table target differs')
    entries={x['entry'] for x in selected};pending=list(entries)
    # Shared 43AE30 tail is already in each relevant root's local graph; name it
    # separately as a provenance node without inferring another call boundary.
    reviewed={};pcs=set()
    while pending:
        entry=pending.pop()
        if entry in reviewed:continue
        graph=graphs[str(entry)]
        require(graph['static_local_branch_decode_closed'] and not graph['import_sites'] and not graph['unresolved_controls'] and not graph['FS_sites'] and not graph['MMX_SSE_sites'] and not graph['unclassified_executable_literals'],'Only closed selected direct graph admitted')
        reviewed[entry]=graph;pcs.update(graph['instruction_pcs'])
        for call in graph['direct_calls']:
            require(str(call['target']) in graphs,'Required internal callee missing')
            pending.append(call['target'])
    require(len(reviewed)==28 and set(reviewed)==entries|{0x40daf0,0x40db30},'Complete selected direct-call closure differs')
    tail_rows=[rows[str(pc)] for pc in graphs[str(0x43aec0)]['instruction_pcs'] if 0x43ae30<=pc<=0x43ae48]
    require(len(tail_rows)==10 and tail_rows[0]['pc']==0x43ae30 and tail_rows[-1]['pc']==0x43ae48 and tail_rows[-1]['mnemonic']=='ret' and
            all(a['pc']+a['size']==b['pc'] for a,b in zip(tail_rows,tail_rows[1:])) and
            all(r['mnemonic'] in ('mov','xor') for r in tail_rows[:-1]),'Exact shared tail body is not contiguous/complete')
    reviewed[0x43ae30]={'entry':0x43ae30,'instruction_pcs':[r['pc'] for r in tail_rows],'direct_calls':[],
        'returns':[{'pc':0x43ae48,'mnemonic':'ret','operands':''}],'static_local_branch_decode_closed':True,
        'provenance':'Complete contiguous fallthrough tail subset already included in frozen root43AEC0 graph'}
    instructions=[rows[str(pc)] for pc in sorted(pcs)]
    require(all(not (row['pc']<CAPTURE+5 and CAPTURE<row['pc']+row['size']) for row in instructions),'Authored capture broker overlaps selected original instruction')
    code_pages=sorted({row['pc']&~4095 for row in instructions})
    require(code_pages==[0x40d000,0x410000,0x413000,0x43a000,0x467000,0x4ad000,0x4b5000,0x4b7000,0x4c7000,0x4ce000,0x4cf000],'Reviewed RX page union differs')
    sparse={address:bytearray(b'\xcc'*4096) for address in code_pages}
    encoded=[]
    for row in instructions:
        pc,size=row['pc'],row['size'];page=pc&~4095
        require((pc+size-1)&~4095==page,'Selected instruction crosses sparse page')
        offset,_=image.rva_range(pc-image.image_base,size);actual=data[offset:offset+size]
        require(actual==bytes.fromhex(row['bytes']),'Exact instruction/image binding differs')
        sparse[page][pc&4095:(pc&4095)+size]=actual
        encoded.append((pc,size,offset))
    records=[(a,1,bytes(sparse[a])) for a in code_pages]
    records += [(a,2 if a in WRITABLE else 0,page_bytes(image,a)) for a in DATA_PAGES]
    records.append((STACK,2,b'\xa5'*4096))
    require(len(records)==22 and sparse[CAPTURE&~4095][CAPTURE&4095:(CAPTURE&4095)+5]==b'\xcc'*5,'Sparse broker admission differs')
    pack=b'MW4MXP01'+struct.pack('<I',len(records))+b''.join(struct.pack('<II',a,p)+b for a,p,b in records)
    out.mkdir(parents=True);(out/'pages.bin').write_bytes(pack)
    spans=[]
    for pc,size,offset in encoded:
        i=code_pages.index(pc&~4095);spans.append((pc,size,offset,12+i*4104+8+(pc&4095)))
    header=['#pragma once','#include <array>','#include <cstdint>','namespace mw34::m4_mixed_original {',
            'inline constexpr char pack_sha[]="'+hashlib.sha256(pack).hexdigest()+'";',
            'inline constexpr std::size_t pack_size='+str(len(pack))+';',
            'inline constexpr std::array<std::uint32_t,26> entries{'+','.join(hex(x['entry']) for x in selected)+'};',
            'inline constexpr std::array<std::uint32_t,26> table_slots{'+','.join(hex(x['slot']) for x in selected)+'};',
            'inline constexpr std::array<std::uint32_t,22> page_bases{'+','.join(hex(a) for a,p,b in records)+'};',
            'inline constexpr std::array<std::uint32_t,22> page_permissions{'+','.join(str(p) for a,p,b in records)+'};',
            'struct CodeBinding {std::uint32_t pc,size,image_offset,pack_offset;};',
            'inline constexpr std::array<CodeBinding,'+str(len(spans))+'> code_bindings{{'+','.join('{'+','.join(hex(v) for v in s)+'}' for s in spans)+'}};','}']
    (out/'spec.hpp').write_text('\n'.join(header)+'\n',encoding='utf-8')
    result={'schema_version':1,'scope':'Sparse original-only connected selected26 roots; no intervening table callbacks/services/full M4 admission',
            'image':bind(image_path),'inventory_bindings':pin_doc['bindings']+[bind(inventory/'pins.json')],
            'selected_table_slots':[{'slot':x['slot'],'entry':x['entry']} for x in selected],
            'graph_nodes':list(sorted(reviewed)),'graphs':[reviewed[a] for a in sorted(reviewed)],'instructions':instructions,
            'capture_broker':{'address':CAPTURE,'size':5,'kind':'Authored JMP to hardware capture; not original game code','disjoint_from_all_selected_instructions':True},
            'code_pages':code_pages,'pages':[{'address':a,'permission':p,'sha256':hashlib.sha256(b).hexdigest(),'origin':'authored A5 stack' if a==STACK else 'exact selected instruction bytes plus INT3 trap fill' if p==1 else 'exact image file bytes and PE zero fill'} for a,p,b in records],
            'pack':bind(out/'pages.bin'),'header':bind(out/'spec.hpp'),'code_bindings':spans,
            'source':bind(__file__),'PE_parser':bind(ROOT/'tools/analysis/pe.py')}
    (out/'extraction.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({'roots':len(selected),'graphs':len(reviewed),'instructions':len(instructions),'pages':len(records),'pack_bytes':len(pack),'output':str(out)}))
if __name__=='__main__':main()
