"""Performance: skip the remaster hook chain for guest calls that have no hook.

Every lifted guest CALL goes Stage::called -> Stage::enter, which ran hud_capture,
hud_intercept and then remaster_body / remaster_body_inner: about 50 target
comparisons and several lazy-setting calls before reaching the body. A mission
frame runs ~80,000 such calls; the stress-replay profile put ~22% of the main
thread in this dispatch glue.

Each hook in that chain is selected by `target==<address>`. This script
collects those addresses from the current host source (remaster_body through
remaster_body_inner, hud_intercept, hud_capture) into a bitmap over the game image.
enter() now runs the chain only for a hooked address (or any address outside the
game image), and calls other bodies directly. The call/return bookkeeping (return
words, depth, SEH test, GuestReturn unwinding) is unchanged.

The script refuses to apply if any use of `target` in that code is not an
equality with a constant or a pass-through, so a range- or table-selected hook
cannot be skipped silently. It must be the LAST host edit applied: hooks added
to the chain afterwards would not be in the bitmap.

Stage::load (4-byte checked guest read) also takes the inline cached-region
pointer that Stage::read already uses before the out-of-line GuestMemory call;
the value and fault behaviour are identical.
"""
from pathlib import Path
import argparse, re

def edit(path,old,new,count=1):
    text=path.read_text()
    if text.count(old)!=count:raise RuntimeError(f'Expected {count} dispatch anchor(s) in {path.name}: {old[:80]}')
    path.write_text(text.replace(old,new))

# hud_capture selects by `target!=` on its first line (the region taken for it); its other uses of `target` are values.
ALLOWED=re.compile(r'target[!=]=0x[0-9a-f]+|unsigned target|\(s,target,|,target\)|\(target\)|target_marker_update_owner|text_hooks\(target\)|host\.frames,target,why|other-global-target"')

def hook_region(text,start,end):
    a=text.index(start);b=text.index(end,a);return text[a:b]

def collect(host):
    m=(host/'mfc_stage.hpp').read_text();g=(host/'gpu_hud.inc').read_text()
    regions=[hook_region(m,' void*remaster_body(State*s,unsigned target',' void*enter(State*s,unsigned target'),
             hook_region(m,' void hud_capture(unsigned target)','\n'),
             hook_region(g,'bool hud_intercept(unsigned target','\n// FPS/frame-time overlay')]
    found=set()
    for r in regions:
        spans=[(x.start(),x.end()) for x in ALLOWED.finditer(r)]
        for k in re.finditer(r'\btarget\b',r):
            if not any(a<=k.start()<b for a,b in spans):
                raise RuntimeError('Hook selected by something other than an address equality: '+' '.join(r[max(0,k.start()-30):k.end()+30].split()))
        found|={int(x,16) for x in re.findall(r'target[!=]=(0x[0-9a-f]+)',r)}
    return sorted(found)

def apply(host):
    addrs=collect(host)
    inside=[a for a in addrs if 0x400000<=a<0x600000]
    lst=','.join(hex(a) for a in inside)
    m=host/'mfc_stage.hpp'
    helper=(' // Generated by apply_dispatch_fast.py from the hook chain below/above: game-image addresses that have a hook.\n'
            ' // Other game-image calls go straight to their lifted body; addresses outside the image always take the chain.\n'
            ' static bool dispatch_hooked(unsigned t){static const auto bits=[]{std::vector<std::uint64_t>b((0x600000-0x400000)/64);for(unsigned a:{'+lst+'})b[(a-0x400000)>>6]|=1ULL<<(a&63);return b;}();\n'
            '  if(t<0x400000||t>=0x600000)return true;return ((bits[(t-0x400000)>>6]>>(t&63))&1)!=0;}\n'
            ' void*enter(State*s,unsigned target,void*p,Body body){')
    edit(m,' void*enter(State*s,unsigned target,void*p,Body body){',helper)
    edit(m,'if(hud_log)hud_capture(target);{void*r{};if(hud_intercept(target,p,r))return r;}',
           'const bool hooked_=dispatch_hooked(target);if(hooked_){if(hud_log)hud_capture(target);void*r{};if(hud_intercept(target,p,r))return r;}')
    edit(m,'max_depth=std::max(max_depth,depth);++bodies;return remaster_body(s,target,p,body);}}',
           'max_depth=std::max(max_depth,depth);++bodies;return hooked_?remaster_body(s,target,p,body):body(s,target,p);}}')
    edit(m,'try{return remaster_body(s,target,p,body);}catch(const GuestReturn&r){if(r.frame!=mine)throw;depth=mine;return p;}}',
           'try{return hooked_?remaster_body(s,target,p,body):body(s,target,p);}catch(const GuestReturn&r){if(r.frame!=mine)throw;depth=mine;return p;}}')
    edit(m,' unsigned load(unsigned a){unsigned v{};bool bad{};try{',
           ' unsigned load(unsigned a){unsigned v{};if(const auto*fp=guest_fast_pointer(&runtime.memory(),a,4,Permissions::read)){std::memcpy(&v,fp,4);return v;}bool bad{};try{')
    print(f'dispatch_hooked: {len(inside)} hooked game addresses ({len(addrs)-len(inside)} outside the image)')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('host_source',type=Path);apply(p.parse_args().host_source)
